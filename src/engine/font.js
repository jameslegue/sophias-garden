// GLYPHS[ch] = list of [x, y] pixels that are on.
export const GLYPHS = {};
for (const [ch, s] of Object.entries(RAW)) {
  const px = [];
  s.split(' ').forEach((row, y) => [...row].forEach((c, x) => { if (c === '#') px.push([x, y]); }));
  GLYPHS[ch] = px;
}
